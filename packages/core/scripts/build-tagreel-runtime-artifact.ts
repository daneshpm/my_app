import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildSync } from "esbuild";
import {
  TAGREEL_RUNTIME_ARTIFACTS,
  TAGREEL_RUNTIME_CONTRACT,
  loadTagreelRuntimeSource,
} from "../src/inline-scripts/tagreel";
import { writeGeneratedFile } from "./writeGeneratedFile.js";

const thisDir = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(thisDir, "../dist");
const iifePath = resolve(distDir, TAGREEL_RUNTIME_ARTIFACTS.iife);
const esmPath = resolve(distDir, TAGREEL_RUNTIME_ARTIFACTS.esm);
const manifestPath = resolve(distDir, TAGREEL_RUNTIME_ARTIFACTS.manifest);

const runtimeSourceRaw = loadTagreelRuntimeSource();
if (runtimeSourceRaw === null) {
  throw new Error("Cannot build runtime artifact: entry.ts not found at expected path");
}
const runtimeSource = `${runtimeSourceRaw}\n`;
const runtimeSha256 = createHash("sha256").update(runtimeSource, "utf8").digest("hex");
const buildId = process.env.TAGREEL_RUNTIME_BUILD_ID?.trim() || "dev";
const runtimeEntryPath = resolve(thisDir, "../src/runtime/entry.ts");
const esmBuild = buildSync({
  entryPoints: [runtimeEntryPath],
  bundle: true,
  write: false,
  platform: "browser",
  format: "esm",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
});
const esmSource = `${esmBuild.outputFiles[0]?.text ?? ""}\n`;

const manifest = {
  version: process.env.TAGREEL_RUNTIME_VERSION?.trim() || "0.1.0",
  buildId,
  sha256: runtimeSha256,
  artifacts: {
    iife: TAGREEL_RUNTIME_ARTIFACTS.iife,
    esm: TAGREEL_RUNTIME_ARTIFACTS.esm,
  },
  contract: TAGREEL_RUNTIME_CONTRACT,
};

writeGeneratedFile(iifePath, runtimeSource);
writeGeneratedFile(esmPath, esmSource);
writeGeneratedFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

// ── Generate src/generated/runtime-inline.ts ──────────────────────────────
// This file is compiled by tsc into dist/ and provides the production-safe
// getTagreelRuntimeScript() that returns the IIFE as a string constant —
// no esbuild, no file I/O, no import.meta.url arithmetic.
const inlineModulePath = resolve(thisDir, "../src/generated/runtime-inline.ts");
const escapedSource = JSON.stringify(runtimeSourceRaw);
writeGeneratedFile(
  inlineModulePath,
  [
    "// AUTO-GENERATED by scripts/build-tagreel-runtime-artifact.ts — do not edit",
    `const RUNTIME_IIFE: string = ${escapedSource};`,
    "",
    "/**",
    " * Returns the pre-built tagreel runtime IIFE as a string constant.",
    " * This is the production-safe path: no esbuild, no file I/O,",
    " * no import.meta.url arithmetic.",
    " */",
    "export function getTagreelRuntimeScript(): string {",
    "  return RUNTIME_IIFE;",
    "}",
    "",
  ].join("\n"),
);

console.log(
  JSON.stringify({
    event: "tagreel_runtime_artifacts_generated",
    buildId,
    distDir,
    iifePath,
    esmPath,
    manifestPath,
    inlineModulePath,
    sourceBytes: Buffer.byteLength(runtimeSource, "utf8"),
    esmBytes: Buffer.byteLength(esmSource, "utf8"),
    sha256: runtimeSha256,
  }),
);
